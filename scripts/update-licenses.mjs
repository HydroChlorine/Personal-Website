import { readFile, writeFile, readdir, mkdir, access } from 'node:fs/promises'
import path from 'node:path'

// Run from the repository root after changing/installing dependencies.
const inventoryDirectory = 'third-party-licenses'
const publicDirectory = 'public/licenses'
await mkdir(inventoryDirectory, { recursive: true })
await mkdir(publicDirectory, { recursive: true })
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'))
const records = []
const notices = []
for (const packagePath of Object.keys(lock.packages)) {
  if (!packagePath) continue
  const metadataPath = path.join(packagePath, 'package.json')
  try {
    await access(metadataPath)
  } catch {
    continue
  } // Platform-specific optional dependencies.
  const metadata = JSON.parse(await readFile(metadataPath, 'utf8'))
  let licenseRoot = packagePath
  let licenseOrigin = ''
  let files = (await readdir(packagePath, { withFileTypes: true }))
    .filter(
      (entry) => entry.isFile() && /license|notice|copyright/i.test(entry.name),
    )
    .map((entry) => entry.name)
    .sort()
  // Native platform packages may ship only a binary. Use notices from an
  // explicitly known parent only when version, license, and repository match.
  const parentName = metadata.name.startsWith('@oxlint/binding-')
    ? 'oxlint'
    : metadata.name.startsWith('@rolldown/binding-')
      ? 'rolldown'
      : null
  if (!files.length && parentName) {
    const parentPath = path.join('node_modules', parentName)
    const parent = JSON.parse(
      await readFile(path.join(parentPath, 'package.json'), 'utf8'),
    )
    if (
      parent.version === metadata.version &&
      parent.license === metadata.license &&
      parent.repository?.url === metadata.repository?.url
    ) {
      licenseRoot = parentPath
      files = (await readdir(parentPath, { withFileTypes: true }))
        .filter(
          (entry) =>
            entry.isFile() && /license|notice|copyright/i.test(entry.name),
        )
        .map((entry) => entry.name)
        .sort()
      licenseOrigin = ` (from ${parentName} ${parent.version}, matching repository and release)`
    }
  }
  if (!files.length)
    throw new Error(
      `No shipped license found for ${metadata.name}; review manually.`,
    )
  const saved = []
  for (const filename of files) {
    const text = await readFile(path.join(licenseRoot, filename), 'utf8')
    const destination = `${metadata.name.replaceAll('/', '__').replaceAll('@', '')}--${filename}`
    await writeFile(path.join(inventoryDirectory, destination), text)
    saved.push(`[${destination}](${destination})`)
    notices.push(
      `===== ${metadata.name} ${metadata.version} / ${filename}${licenseOrigin} =====\n\n${text}\n`,
    )
  }
  records.push(
    `| ${metadata.name} | ${metadata.version} | ${metadata.license ?? 'See notices'} | ${saved.join(', ')}${licenseOrigin} |`,
  )
}
await writeFile(
  path.join(inventoryDirectory, 'README.md'),
  [
    '# Dependency license inventory',
    '',
    'Generated by `npm run licenses` from installed packages and the lockfile. Copies preserve shipped license and notice text. No license is granted here for the site as a whole.',
    '',
    '| Package | Version | Declared license | Copied notices |',
    '| --- | --- | --- | --- |',
    ...records.sort(),
    '',
  ].join('\n'),
)
await writeFile(
  path.join(publicDirectory, 'THIRD_PARTY_NOTICES.txt'),
  'THIRD-PARTY SOFTWARE NOTICES\n\nLicenses and copyright notices for installed dependencies, including build tools. Original project code and artwork are separate.\n\n' +
    notices.join('\n'),
)
console.log(
  `Recorded shipped notices for ${records.length} installed packages.`,
)
